#!/usr/bin/env python3
"""Generate Java constant classes from Scintilla.h and SciLexer.h.

Usage: python3 tools/gen_constants.py
Rerun after updating third_party/scintilla or third_party/lexilla.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/java/io/github/revelationnow/pocketpadpp/scintilla"
DEFINE = re.compile(r"^#define\s+([A-Z][A-Z0-9_]*)\s+(.+?)\s*$")
NUMBER = re.compile(r"^-?(0[xX][0-9a-fA-F]+|\d+)$")
TOKEN = re.compile(r"[A-Z][A-Z0-9_]*")


def constants(header):
    seen = {}
    for line in header.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.split("//")[0]
        m = DEFINE.match(line)
        if not m:
            continue
        name, value = m.group(1), m.group(2).strip()
        if name in seen or name.endswith("_H"):
            continue
        if NUMBER.match(value):
            seen[name] = value
        elif re.fullmatch(r"[A-Z0-9_xXa-fA-F\s()|+\-<]+", value) and all(t in seen for t in TOKEN.findall(value)):
            # Expression built only from constants defined earlier in the same header.
            seen[name] = value
    return seen


def emit(cls, header, doc):
    lines = [
        "// Generated by tools/gen_constants.py - do not edit.",
        "package io.github.revelationnow.pocketpadpp.scintilla;",
        "",
        f"/** {doc} */",
        f"public final class {cls} {{",
        f"    private {cls}() {{}}",
        "",
    ]
    for name, value in constants(header).items():
        lines.append(f"    public static final int {name} = {value};")
    lines.append("}")
    (OUT / f"{cls}.java").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines) - 8


if __name__ == "__main__":
    n1 = emit("Sci", ROOT / "third_party/scintilla/include/Scintilla.h",
              "Scintilla message numbers and constants (from Scintilla.h).")
    n2 = emit("SciLex", ROOT / "third_party/lexilla/include/SciLexer.h",
              "Lexer ids and style numbers (from SciLexer.h).")
    print(f"Sci: {n1} constants, SciLex: {n2} constants")
