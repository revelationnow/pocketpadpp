#!/usr/bin/env python3
"""Generate the tables the Lua scripting layer is built on.

Usage: python3 tools/gen_lua_iface.py [/path/to/notepad-plus-plus]

From Scintilla.iface (and Lexilla's LexicalStyles.iface) it writes, under app/src/main/assets/lua/:
  iface.lua      every Scintilla function and property a script may use, as calls to F, P and X
  constants.lua  every SCI_, SC_, SCN_, SCE_... constant by name
With a Notepad++ checkout it also writes
  menu.tsv       Notepad++'s menu command ids (IDM_...) with their numbers and menu paths,
                 so that npp:MenuCommand(IDM_EDIT_JOIN_LINES) can find the same command here.
  langs.tsv      Notepad++'s language types (L_...) with their numbers and names, for npp.BufferLangType.
Rerun after updating third_party/scintilla or third_party/lexilla.

The shape of the script interface follows SciTE's Lua extension, which Notepad++'s LuaScript plugin
uses too: functions keep their names, a getter and setter pair becomes a property (GetTabWidth and
SetTabWidth are editor.TabWidth, StyleGetBold and StyleSetBold are editor.StyleBold[style]).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/lua"
FEATURE = re.compile(r"^(fun|get|set)\s+(\w+)\s+(\w+)=(\d+)\(([^,)]*),([^)]*)\)")
EVENT = re.compile(r"^evt\s+\w+\s+(\w+)=(\d+)\(")
VALUE = re.compile(r"^val\s+(\w+)=(-?(?:0[xX][0-9a-fA-F]+|\d+))\s*$")

# Types a script cannot supply or receive: raw pointers and the structures some messages take.
UNSCRIPTABLE = {"pointer", "textrange", "textrangefull", "findtext", "findtextfull", "formatrange", "formatrangefull"}


def kind(type_name, name=""):
    """One letter for how a value crosses between Lua and Scintilla."""
    if not type_name or type_name == "void":
        return "v"
    if type_name in UNSCRIPTABLE:
        return "x"
    if type_name in ("string", "cells"):
        return "s"
    if type_name == "stringresult":
        return "r"
    if type_name == "bool":
        return "b"
    if type_name == "keymod":
        return "k"
    if type_name in ("int", "position") and name == "length":
        return "L"
    return "i"


def param(text):
    parts = text.split("=")[0].split()
    return (parts[0], parts[1] if len(parts) > 1 else "") if parts else ("", "")


def features(iface):
    category = ""
    for line in iface.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("cat "):
            category = line[4:].strip()
        m = FEATURE.match(line)
        if m and category != "Deprecated":
            p1, p2 = param(m.group(5)), param(m.group(6))
            yield m.group(1), m.group(3), int(m.group(4)), kind(m.group(2)), kind(*p1), kind(*p2)


def properties(found):
    """Getter and setter pairs with the same shape, as (name, get, set, value, index, flags)."""
    getters, setters = {}, {}
    for what, name, message, ret, p1, p2 in found:
        if what == "get":
            prop = name.replace("Get", "", 1)
            if p2 == "r":
                # A string: with the length asked for first, or indexed by the first parameter.
                shape = ("s", None, 2) if p1 in ("L", "v") else ("s", p1, 0)
            elif p2 == "v" and ret in ("i", "b"):
                shape = (ret, None if p1 == "v" else p1, 0)
            else:
                continue
            if shape[1] in ("x", "k", "r"):
                continue
            getters[prop] = (message,) + shape
        elif what == "set":
            prop = name.replace("Set", "", 1)
            if p2 == "v":
                shape = (p1, None, 0)
            elif p1 == "v":
                shape = (p2, None, 1)      # the value travels in the second parameter
            else:
                shape = (p2, p1, 0)
            if shape[0] not in ("i", "b", "s", "L") or shape[1] in ("x", "k", "r", "v"):
                continue
            value = "i" if shape[0] == "L" else shape[0]
            index = "i" if shape[1] == "L" else shape[1]
            setters[prop] = (message, value, index, shape[2])
    for prop in sorted(set(getters) | set(setters)):
        g, s = getters.get(prop), setters.get(prop)
        if g and s and ((g[2] is None) != (s[2] is None) or g[1] != s[1]):
            # Not a matching pair (GetStyleAt against SetStyling, say): the functions remain.
            continue
        one = g or s
        flags = (g[3] if g else 0) | (s[3] if s else 0)
        yield prop, g[0] if g else 0, s[0] if s else 0, one[1], (g or s)[2], flags


def lua(value):
    return "nil" if value is None else f'"{value}"' if isinstance(value, str) else str(value)


def write_iface():
    found = list(features(ROOT / "third_party/scintilla/include/Scintilla.iface"))
    lines = ["-- Generated by tools/gen_lua_iface.py from Scintilla.iface - do not edit.",
             "-- F(name, message, returns, first, second): a function. P(name, getter, setter, value, index, flags): a property.",
             "-- X(name): exists in Scintilla but takes or returns something a script cannot hold.",
             "local F, P, X = ..."]
    functions = blocked = 0
    props = list(properties(found))
    names = {prop[0] for prop in props}
    for what, name, message, ret, p1, p2 in found:
        if "x" in (ret, p1, p2):
            lines.append(f'X("{name}")')
            blocked += 1
        elif what != "fun" and name in names:
            # A getter whose name is the property's own (LinesOnScreen): editor.LinesOnScreen is the value.
            continue
        else:
            lines.append(f'F("{name}",{message},"{ret}","{p1}","{p2}")')
            functions += 1
    for prop, getter, setter, value, index, flags in props:
        lines.append(f'P("{prop}",{getter},{setter},"{value}",{lua(index)},{flags})')
    (OUT / "iface.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")

    constants = {}
    for what, name, message, ret, p1, p2 in found:
        constants.setdefault("SCI_" + name.upper(), message)
    for iface in (ROOT / "third_party/scintilla/include/Scintilla.iface", ROOT / "third_party/lexilla/include/LexicalStyles.iface"):
        for line in iface.read_text(encoding="utf-8", errors="replace").splitlines():
            m = VALUE.match(line)
            if m:
                constants.setdefault(m.group(1), int(m.group(2), 0))
            m = EVENT.match(line)
            if m:
                constants.setdefault("SCN_" + m.group(1).upper(), int(m.group(2)))
    return functions, blocked, len(props), constants


def menu_commands(npp):
    """(id name, number, menu path) for every item of Notepad++'s main menu."""
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import feature_map
    source = pathlib.Path(npp) / "PowerEditor/src"
    values = {}
    for line in (source / "menuCmdID.h").read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"\s*#define\s+(\w+)\s+(.+?)\s*(//.*)?$", line)
        if m and re.fullmatch(r"[\w\s()+\-]+", m.group(2)):
            try:
                values[m.group(1)] = eval(m.group(2), {"__builtins__": {}}, values)
            except Exception:
                pass
    rc = (source / "Notepad_plus.rc").read_text(encoding="utf-8", errors="replace")
    seen = set()
    for path, label, command in feature_map.parse_menu(rc):
        if command in seen or command not in values:
            continue
        seen.add(command)
        yield command, values[command], " > ".join(path + [label])


def languages(npp):
    """(id name, number, language name, display name) in the order of Notepad++'s LangType, which numbers them."""
    cpp = (pathlib.Path(npp) / "PowerEditor/src/ScintillaComponent/ScintillaEditView.cpp").read_text(encoding="utf-8", errors="replace")
    table = cpp[cpp.index("ScintillaEditView::_langNameInfoArray"):]
    table = table[:table.index("};")]
    rows = re.findall(r'\{L"([^"]*)",\s*L"([^"]*)",\s*L"[^"]*",\s*(L_\w+),\s*"[^"]*"\}', table)
    return [(lang_id, number, name, display) for number, (name, display, lang_id) in enumerate(rows)]


def table(name, rows):
    """Writes the rows as a tab-separated file, or reads back the one written before."""
    path = OUT / name
    if rows is not None:
        path.write_text("".join("\t".join(str(cell) for cell in row) + "\n" for row in rows), encoding="utf-8")
    elif path.exists():
        rows = [line.split("\t") for line in path.read_text(encoding="utf-8").splitlines()]
    return rows or []


def main():
    functions, blocked, props, constants = write_iface()
    npp = sys.argv[1] if len(sys.argv) > 1 else None
    rows = table("menu.tsv", list(menu_commands(npp)) if npp else None)
    langs = table("langs.tsv", languages(npp) if npp else None)
    for name, number, *_ in rows + langs:
        constants.setdefault(name, int(number))
    lines = ["-- Generated by tools/gen_lua_iface.py - do not edit.", "return {"]
    lines += [f"{name}={value}," for name, value in sorted(constants.items())]
    lines.append("}")
    (OUT / "constants.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{functions} functions, {props} properties, {blocked} not scriptable, {len(constants)} constants, "
          f"{len(rows)} menu commands, {len(langs)} languages")


if __name__ == "__main__":
    main()
