#!/usr/bin/env python3
"""Writes the Pocketpad++ logo from one description of its shapes:

  docs/logo.svg                                         for the README and anywhere else
  app/src/main/res/drawable/ic_launcher_foreground.xml  the launcher icon's foreground layer
  app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml    the adaptive icon
  app/src/main/res/values/ic_launcher.xml               its background colour

The mark is a notepad tucked into a pocket that carries the "++". Run from the repository root.
"""
import pathlib

BACKGROUND = "#17332D"
POCKET = "#33B56C"
HEM = "#279457"
STITCH = "#BFE8D0"
SHEET = "#FFFFFF"
BINDING = "#F2A83B"
RULE = "#C8D5CF"
PLUS = "#FFFFFF"

PAD_TILT = -7          # degrees, about the point below
PAD_PIVOT = (256, 230)


def rrect(x, y, w, h, r):
    """A rounded rectangle as path data that both SVG and Android vector drawables understand."""
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} V{y + r} "
            f"A{r},{r} 0 0 1 {x + r},{y} Z")


def plus(cx, cy, arm, thick, r):
    return rrect(cx - arm / 2, cy - thick / 2, arm, thick, r) + " " + rrect(cx - thick / 2, cy - arm / 2, thick, arm, r)


# (colour, path data) in drawing order. The pad is drawn tilted; everything else upright.
PAD = [
    (SHEET, rrect(156, 92, 200, 250, 14)),
    (BINDING, "M170,92 H342 A14,14 0 0 1 356,106 V134 H156 V106 A14,14 0 0 1 170,92 Z"),
    (RULE, rrect(182, 160, 148, 10, 5)),
    (RULE, rrect(182, 190, 148, 10, 5)),
    (RULE, rrect(182, 220, 104, 10, 5)),
]
FRONT = [
    (POCKET, "M112,262 Q112,250 124,250 H388 Q400,250 400,262 V352 Q400,374 381,386 L275,450 "
             "Q256,461 237,450 L131,386 Q112,374 112,352 Z"),
    (HEM, "M112,262 Q112,250 124,250 H388 Q400,250 400,262 V290 H112 Z"),
]
FRONT += [(STITCH, rrect(132 + i * 28, 300, 16, 5, 2.5)) for i in range(9)]
FRONT += [(PLUS, plus(212, 362, 64, 20, 7)), (PLUS, plus(300, 362, 64, 20, 7))]


def svg():
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Pocketpad++">',
           f'  <rect width="512" height="512" rx="116" fill="{BACKGROUND}"/>',
           f'  <g transform="rotate({PAD_TILT} {PAD_PIVOT[0]} {PAD_PIVOT[1]})">']
    out += [f'    <path fill="{colour}" d="{d}"/>' for colour, d in PAD]
    out += ['  </g>']
    out += [f'  <path fill="{colour}" d="{d}"/>' for colour, d in FRONT]
    out += ['</svg>', '']
    return "\n".join(out)


def foreground():
    # The 512-unit drawing sits in the middle two thirds of the icon, inside the area every launcher shows.
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/gen_logo.py; edit the shapes there. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp"', '    android:height="108dp"',
           '    android:viewportWidth="768"', '    android:viewportHeight="768">',
           '    <group android:translateX="128" android:translateY="128">',
           f'        <group android:rotation="{PAD_TILT}" android:pivotX="{PAD_PIVOT[0]}" android:pivotY="{PAD_PIVOT[1]}">']
    out += [f'            <path android:fillColor="{colour}" android:pathData="{d}" />' for colour, d in PAD]
    out += ['        </group>']
    out += [f'        <path android:fillColor="{colour}" android:pathData="{d}" />' for colour, d in FRONT]
    out += ['    </group>', '</vector>', '']
    return "\n".join(out)


ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
'''

COLOURS = f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
'''

root = pathlib.Path(".")
for path, text in [
    ("docs/logo.svg", svg()),
    ("app/src/main/res/drawable/ic_launcher_foreground.xml", foreground()),
    ("app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE),
    ("app/src/main/res/values/ic_launcher.xml", COLOURS),
]:
    target = root / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print("wrote", path)
