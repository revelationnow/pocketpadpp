#!/usr/bin/env python3
"""Extract Notepad++'s language table from its sources and copy its language/style definitions.

Usage: python3 tools/gen_npp_tables.py /path/to/notepad-plus-plus

Writes app/src/main/assets/npp/languages.tsv with one row per language:
    name, display name, Lexilla lexer, kind, keyword-list mask, lexer properties
and copies langs.model.xml, stylers.model.xml and the bundled themes next to it, unmodified.

"kind" says which of Notepad++'s lexer setup routines the language uses; the generic one sends
keyword class N to keyword set N for every bit set in the mask (see ScintillaEditView::setLexer).
"""
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/npp"

SPECIAL = {
    "L_C": "cpp", "L_CPP": "cpp", "L_JAVA": "cpp", "L_RC": "cpp", "L_CS": "cpp", "L_FLASH": "cpp",
    "L_SWIFT": "cpp", "L_GOLANG": "cpp",
    "L_JAVASCRIPT": "js", "L_JS_EMBEDDED": "js",
    "L_TCL": "tcl", "L_OBJC": "objc",
    "L_PHP": "html", "L_ASP": "html", "L_JSP": "html", "L_HTML": "html", "L_XML": "xml",
    "L_JSON": "json", "L_JSON5": "json5",
    "L_TYPESCRIPT": "typescript", "L_BASH": "bash",
    "L_TEXT": "text", "L_ASCII": "text",
}
SKIP = {"L_USER", "L_EXTERNAL", "L_SEARCHRESULT"}


def main(npp):
    src = pathlib.Path(npp) / "PowerEditor/src"
    cpp = (src / "ScintillaComponent/ScintillaEditView.cpp").read_text(encoding="utf-8", errors="replace")
    header = (src / "ScintillaComponent/ScintillaEditView.h").read_text(encoding="utf-8", errors="replace")

    table = cpp[cpp.index("ScintillaEditView::_langNameInfoArray"):]
    table = table[:table.index("};")]
    rows = re.findall(r'\{L"([^"]*)",\s*L"([^"]*)",\s*L"[^"]*",\s*(L_\w+),\s*"([^"]*)"\}', table)

    lists = {name: 1 << int(bit) for name, bit in re.findall(r"#define (LIST_\d) (\d+)", header)
             for bit in [str(int(bit).bit_length() - 1)]}
    lists["LIST_NONE"] = 0

    masks, props = {}, {}
    for _, body in re.findall(r"void set(\w+)Lexer\([^)]*\)\s*(?:const\s*)?\{(.*?)\n\t\}", header, re.S):
        call = re.search(r"setLexer\((L_\w+),\s*([^,)]+)", body)
        if not call:
            continue
        lang_ids = [call.group(1)]
        if call.group(1) == "L_id":  # setPropsLexer covers both
            lang_ids = ["L_PROPS", "L_INI"]
        mask = sum(lists[t.strip()] for t in call.group(2).split("|"))
        found = re.findall(r'SCI_SETPROPERTY, reinterpret_cast<WPARAM>\("([^"]+)"\), reinterpret_cast<LPARAM>\("([^"]*)"\)', body)
        for lang_id in lang_ids:
            masks[lang_id] = mask
            props[lang_id] = found

    lines = ["# Generated by tools/gen_npp_tables.py from Notepad++ sources - do not edit.",
             "# name\tdisplay\tlexer\tkind\tmask\tproperties"]
    for name, display, lang_id, lexer in rows:
        if lang_id in SKIP or not name:
            continue
        kind = SPECIAL.get(lang_id, "generic")
        if kind == "generic" and lang_id not in masks:
            print(f"warning: no setup found for {lang_id} ({name}); using an empty mask", file=sys.stderr)
        mask = masks.get(lang_id, 0)
        prop_text = ";".join(f"{k}={v}" for k, v in props.get(lang_id, []))
        lines.append("\t".join([name, display, lexer, kind, str(mask), prop_text]))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "languages.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for name in ("langs.model.xml", "stylers.model.xml"):
        shutil.copyfile(src / name, OUT / name)
    # Notepad++'s bundled themes, unmodified. Each is a complete style file like stylers.model.xml.
    themes = OUT / "themes"
    themes.mkdir(exist_ok=True)
    for old in themes.glob("*.xml"):
        old.unlink()
    count = 0
    for theme in sorted((pathlib.Path(npp) / "PowerEditor/installer/themes").glob("*.xml")):
        shutil.copyfile(theme, themes / theme.name)
        count += 1
    print(f"{len(lines) - 2} languages, {count} themes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
